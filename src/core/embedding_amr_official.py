"""Official SWAN template normalization and isolated, seeded S2Match scoring.

Only Bank verification uses normalized graphs. Correspondence always uses raw
graphs in embedding_amr.py. This adapter is not the official document z statistic.
"""
from __future__ import annotations

from contextlib import redirect_stderr, redirect_stdout
from dataclasses import dataclass
import importlib.metadata
import importlib.util
import io
import json
import math
from pathlib import Path
import sys
import threading
import warnings

from .embedding_amr import digest
from .embedding_amr_runtime import asset_hashes, file_sha
from .swan_blind_runtime import (
    OFFICIAL, ROOT, RUNTIME, SETTINGS, OfficialNormalizer, fixed_seed, graph_valid, logs,
)
from .swan_blind_protocol import digest as official_digest

_LOCK = threading.RLock()  # S2Match's RNG, logging streams and caches are mutable.


@dataclass(frozen=True)
class OfficialMatch:
    score: float
    template_index: int


class OfficialBankScorer:
    def __init__(self, bank_path, expected_sha256, vectors_path=None):
        self.bank_path = Path(bank_path).resolve()
        self.bank_sha256 = file_sha(self.bank_path)
        if self.bank_sha256 != expected_sha256:
            raise ValueError("Target Bank SHA256 mismatch")
        rows = json.loads(self.bank_path.read_text())
        if not isinstance(rows, list) or not rows:
            raise ValueError("Nonempty official Bank required")
        templates = [r.get("normalized_template_amr") if isinstance(r, dict) else None for r in rows]
        if any(not isinstance(t, str) or not t.strip() or not graph_valid(t) for t in templates):
            raise ValueError("Invalid normalized Bank template")
        if len(set(templates)) != len(templates):
            raise ValueError("Duplicate Bank templates")
        self.templates = tuple(templates)
        self.normalizer = OfficialNormalizer()
        # Reuse the verified source entry point with private module state instead
        # of the legacy global _BANK, which would mix two scorer instances.
        spec = importlib.util.spec_from_file_location("_embedding_amr_s2match", RUNTIME / "s2match.py")
        module = importlib.util.module_from_spec(spec)
        sys.path.insert(0, str(RUNTIME))
        try:
            spec.loader.exec_module(module)
        finally:
            sys.path.remove(str(RUNTIME))
        if Path(module.amr.__file__).resolve() != (RUNTIME / "amr_py3.py").resolve():
            raise RuntimeError("Unexpected S2Match AMR dependency")
        vector_path = Path(vectors_path or ROOT / "vectors/glove.6B.100d.txt").resolve()
        vectors = module.load_vecs(str(vector_path))
        if not vectors:
            raise ValueError("Empty official vector asset")
        module.load_vecs = lambda _: vectors
        if module.iteration_num != SETTINGS["score"]["hillclimbing_iterations"]:
            raise RuntimeError("Unexpected S2Match iteration setting")
        self.matcher = module
        import en_core_web_sm
        model_root = Path(en_core_web_sm.__file__).parent
        self.asset_paths = {
            "official_normalizer": OFFICIAL / "utils/amr_utils.py",
            "s2match": RUNTIME / "s2match.py", "amr_py3": RUNTIME / "amr_py3.py",
            "helpers": RUNTIME / "helpers.py",
            "vectors": vector_path, "propbank": ROOT / ".nltk_data/corpora/propbank.zip",
        }
        self.model_root = model_root
        self.assets = {k: file_sha(p) for k, p in self.asset_paths.items()}
        # Bytecode is generated by Python and is not a model input.
        self.spacy_assets = {k: v for k, v in asset_hashes(model_root).items()
                             if "__pycache__" not in Path(k).parts and not k.endswith(".pyc")}
        self.metadata = {
            "version": "official-swan-bank-adapter/v1", "bank_sha256": self.bank_sha256,
            "bank_size": len(templates), "assets": self.assets,
            "spacy_assets": self.spacy_assets, "settings": SETTINGS["score"],
            "dependencies": {k: importlib.metadata.version(k) for k in
                             ("spacy", "nltk", "numpy", "scipy", "penman")},
            "normalization": "official_template_after_raw_correspondence",
            "pair_seed_serializer": "swan_blind_protocol.digest",
            "all_templates_scored": True,
        }
        self.fingerprint = digest(self.metadata)
        self.memo, self.audit = {}, {}
        self.exact_replays = 0

    def _scores(self, graph):
        scores, diagnostics, events = [], io.StringIO(), []
        module = self.matcher
        with _LOCK, redirect_stderr(diagnostics), redirect_stdout(diagnostics), \
                warnings.catch_warnings(record=True) as caught, \
                logs({"input": 0, "phase": "bank_scoring"}, events, names=("app",)):
            warnings.simplefilter("always")
            old_error, old_debug = module.ERROR_LOG, module.DEBUG_LOG
            module.ERROR_LOG = module.DEBUG_LOG = diagnostics
            try:
                for template in self.templates:
                    seed = int(official_digest(["sha256-graph-bank-v1", graph, template])[:8], 16)
                    with fixed_seed(seed):
                        value = module.compute_s2match_from_strings(
                            graph, template, vectors_file="frozen-vector-cache",
                            similarity_function="cosine", cutoff=.5, diffsense=.5,
                            mwp="split", do_not_mark_quotes=False, verbose=False)[2]
                    scores.append(float(value))
            finally:
                module.ERROR_LOG, module.DEBUG_LOG = old_error, old_debug
        if (caught or events or diagnostics.getvalue() or len(scores) != len(self.templates)
                or any(not math.isfinite(s) or not 0 <= s <= 1 for s in scores)):
            raise RuntimeError("Official Bank diagnostic or invalid score; no partial release")
        return scores

    def score_amr(self, raw):
        key = digest(raw)
        if key not in self.memo:
            first, second = self.normalizer(raw), self.normalizer(raw)
            if first != second:
                raise RuntimeError("Official normalization replay mismatch")
            if not first["normalization_ok"]:
                # Content-dependent official normalization warnings (for example
                # duplicate :time/:timezone triples from timestamp text) make a
                # graph unusable for Bank verification. Exclude this candidate
                # instead of aborting the whole frozen run; its row stays in the
                # complete denominator and contributes no evidence.
                self.memo[key] = None
                self.audit[key] = {"normalization_ok": False,
                                   "exception_type": first.get("exception_type"),
                                   "events": first["events"][:20]}
                return None
            scores = self._scores(first["graph"])
            if scores != self._scores(first["graph"]):
                raise RuntimeError("Official S2Match exact replay mismatch")
            self.exact_replays += 1
            best = max(range(len(scores)), key=scores.__getitem__)
            self.memo[key] = OfficialMatch(scores[best], best)
            self.audit[key] = {"normalized_graph_sha256": digest(first["graph"]),
                               "bank_scores": scores, "exact_replay": True}
        return self.memo[key]

    def verify_assets(self):
        if file_sha(self.bank_path) != self.bank_sha256:
            raise RuntimeError("Bank changed during scoring")
        if any(file_sha(p) != self.assets[k] for k, p in self.asset_paths.items()):
            raise RuntimeError("Official scorer asset drift")
        current = {k: v for k, v in asset_hashes(self.model_root).items()
                   if "__pycache__" not in Path(k).parts and not k.endswith(".pyc")}
        if current != self.spacy_assets:
            raise RuntimeError("Normalizer model drift")
